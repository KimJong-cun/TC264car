#define NAV_ROUTE_PATH_COUNT   ((uint16)(sizeof(s_nav_route_path) / sizeof(s_nav_route_path[0])))

uint16 nav_route_point_count(void)
{
    return NAV_ROUTE_PATH_COUNT;
}

void nav_route_get_point(uint16 index, float *out_x, float *out_y)
{
    uint16 last = (uint16)(NAV_ROUTE_PATH_COUNT - 1u);

    if (index > last)
    {
        index = last;
    }

    *out_x = s_nav_route_path[index].x;
    *out_y = s_nav_route_path[index].y;
}

uint16 nav_route_advance_index(uint16 index, float robot_x, float robot_y)
{
    uint16 last_seg = (uint16)(NAV_ROUTE_PATH_COUNT - 2u);
    float ax, ay, bx, by, sx, sy, len_sq, t;

    while (index < last_seg)
    {
        ax = s_nav_route_path[index].x;
        ay = s_nav_route_path[index].y;
        bx = s_nav_route_path[index + 1u].x;
        by = s_nav_route_path[index + 1u].y;
        sx = bx - ax;
        sy = by - ay;
        len_sq = (sx * sx) + (sy * sy);

        if (len_sq < NAV_ROUTE_SEG_LEN_EPS)
        {
            index++;
            continue;
        }

        t = ((robot_x - ax) * sx + (robot_y - ay) * sy) / len_sq;

        if (t < 1.0f)
        {
            break;
        }

        index++;
    }

    return index;
}

void nav_route_compute_target(uint16 index, float *out_x, float *out_y)
{
    uint16 last = (uint16)(NAV_ROUTE_PATH_COUNT - 1u);
    uint16 i;
    uint16 idx;
    float sum_x = 0.0f;
    float sum_y = 0.0f;

    for (i = 1u; i <= NAV_ROUTE_LOOKAHEAD_POINTS; i++)
    {
        idx = (uint16)(index + i);
        if (idx > last)
        {
            idx = last;
        }

        sum_x += s_nav_route_path[idx].x;
        sum_y += s_nav_route_path[idx].y;
    }

    *out_x = sum_x / (float)NAV_ROUTE_LOOKAHEAD_POINTS;
    *out_y = sum_y / (float)NAV_ROUTE_LOOKAHEAD_POINTS;
}

float nav_route_compute_bearing_deg(float robot_x, float robot_y, float target_x, float target_y)
{
    float dx = target_x - robot_x;
    float dy = target_y - robot_y;

    return atan2f(dx, dy) * NAV_ROUTE_RAD_TO_DEG;
}

uint8 nav_route_is_finished(uint16 index, float robot_x, float robot_y)
{
    uint16 last_seg = (uint16)(NAV_ROUTE_PATH_COUNT - 2u);
    float ax, ay, bx, by, sx, sy, len_sq, t, dx, dy, dist_to_goal;

    if (index < last_seg)
    {
        return 0u;
    }

    ax = s_nav_route_path[last_seg].x;
    ay = s_nav_route_path[last_seg].y;
    bx = s_nav_route_path[last_seg + 1u].x;
    by = s_nav_route_path[last_seg + 1u].y;
    sx = bx - ax;
    sy = by - ay;
    len_sq = (sx * sx) + (sy * sy);

    t = (len_sq < NAV_ROUTE_SEG_LEN_EPS)
        ? 1.0f
        : (((robot_x - ax) * sx + (robot_y - ay) * sy) / len_sq);

    dx = bx - robot_x;
    dy = by - robot_y;
    dist_to_goal = sqrtf(dx * dx + dy * dy);

    return ((t >= 1.0f) || (dist_to_goal < NAV_ROUTE_WP_REACH_M)) ? 1u : 0u;
}
